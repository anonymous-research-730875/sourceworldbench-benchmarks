def get_parser(datapoint: StateDatapoint) -> TestParser:
    """Return the parser for `datapoint`'s base state, or raise.

    Augmentations reuse their base's test command and output format, so they share the
    base's parser; the lookup key is `base_key(datapoint)` (see `sourceworldbench_benchmarks.schema`),
    which every state — base or augmented — resolves to the same value for.

    Every base must declare its parser explicitly. No implicit fallback — silent
    defaults would mask the case where someone adds a state without thinking about how
    its results get parsed.
    """
    key = base_key(datapoint)
    if key not in PARSERS:
        raise KeyError(f"no parser registered for base state {key!r}; add an entry to sourceworldbench_benchmarks.parsers.PARSERS")
    return PARSERS[key]
